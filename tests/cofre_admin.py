"""Cofre das Conexões (v3.6): copiar chaves só com DUPLA verificação (login de Admin total + senha digitada de novo). A chave nunca aparece na tela nem no aparelho (só na área de transferência)."""
import sys, os, re
AQUI = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, AQUI)
from mock import *
from playwright.sync_api import sync_playwright
AXE = open(os.path.join(AQUI, 'axe.min.js')).read()
BASE = os.environ.get("TK_BASE", "http://localhost:8765/")
OK = []; BAD = []
def chk(n, c, e=""):
    (OK if c else BAD).append(n); print(("  ✔ " if c else "  ✘ ") + n + ((" — " + str(e)) if (e and not c) else ""))
DIAL = []
def novo(b, perms=PERMS_ALL, versao="3.6"):
    ctx = b.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True, service_workers="block")
    ctx.add_init_script(SESSION); st = install(ctx, perms=perms, versao=versao)
    ctx.grant_permissions(["clipboard-read", "clipboard-write"], origin=BASE.split("/", 3)[0] + "//" + BASE.split("/", 3)[2])
    for k in ("render", "cloudflare", "onesignal"):
        st["conex"][k].update({"temChave": True, "fim": "1234"})
    st["conex"]["onesignal"]["chaveEnvio"] = True
    pg = ctx.new_page(); erros = []; pg.on("pageerror", lambda e: erros.append(str(e))); pg.on("dialog", lambda d: (DIAL.append((d.type, d.message)), d.accept()))
    pg.goto(BASE + "admin.html"); pg.wait_for_timeout(2600)
    pg.click("#details-ferramentas > summary"); pg.wait_for_timeout(250)
    pg.click("#btn-abrir-conexoes"); pg.wait_for_timeout(1500); pg.evaluate("document.querySelectorAll('#cx-corpo .cx-grupo').forEach(g=>g.open=true)"); pg.wait_for_timeout(300)
    return ctx, pg, st, erros
SEGREDOS = re.compile(r"rnd_FALSO|cfut_FALSO|os_v2_(org|app)_FALSO|IGAA_FALSO|ZERNIO_FALSO|WAF_FALSO")
AS = "[data-cx=cofre-copiar]:not([data-nome^='w:'])"   # itens guardados no Apps Script
with sync_playwright() as p:
    b = p.chromium.launch(args=["--no-sandbox"])
    ctx, pg, st, erros = novo(b)
    print("== Cofre trancado ==")
    chk("cofre aparece trancado, pedindo a senha", pg.locator("#cx-cofre-senha").is_visible() and pg.get_attribute("#cx-cofre-senha", "type") == "password" and pg.locator("[data-cx=cofre-copiar]").count() == 0)
    pg.click("[data-cx=cofre-abrir]"); pg.wait_for_timeout(300)
    chk("sem digitar a senha: frase de erro e nada enviado", "Digite a senha" in pg.inner_text("#cx-msg-cofre") and not st.get("cofre"))
    pg.fill("#cx-cofre-senha", "senha-errada"); pg.click("[data-cx=cofre-abrir]"); pg.wait_for_timeout(500)
    chk("senha errada: recusa, campo limpo, continua trancado", "Senha incorreta" in pg.inner_text("#cx-msg-cofre") and pg.input_value("#cx-cofre-senha") == "" and pg.locator("[data-cx=cofre-copiar]").count() == 0)
    print("== Abrir com a senha certa ==")
    pg.fill("#cx-cofre-senha", "senha-certa"); pg.click("[data-cx=cofre-abrir]"); pg.wait_for_selector("[data-cx=cofre-copiar]")
    chk("abriu: 4 chaves com botão Copiar e contagem regressiva", pg.locator(AS).count() == 4 and "tranca em" in pg.inner_text("#cx-cofre-tempo") or "Cofre aberto" in pg.inner_text("#cx-cofre-tempo"))
    html = pg.content(); ls = pg.evaluate("JSON.stringify(localStorage)+JSON.stringify(sessionStorage)")
    chk("senha digitada e código de abertura fora do HTML e do armazenamento", "senha-certa" not in html and "senha-certa" not in ls and "abc123COFRE" not in html and "abc123COFRE" not in ls)
    pg.evaluate(AXE)
    ax = pg.evaluate("async()=>{const r=await axe.run(document.querySelector('#cx-cofre'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','best-practice']}});return r.violations.map(v=>v.id+' '+v.nodes[0].target.join(' '))}")
    chk("axe — cofre aberto", not ax, ax)
    print("== Copiar ==")
    pg.click("[data-cx=cofre-copiar][data-nome=render]"); pg.wait_for_timeout(700)
    chk("Render: copiada para a área de transferência e avisa", pg.evaluate("navigator.clipboard.readText()") == "rnd_FALSO_PARA_TESTE_123456" and "Copiada" in pg.inner_text("#cx-msg-cofre"))
    pg.click("[data-cx=cofre-copiar][data-nome=onesignalEnvio]"); pg.wait_for_timeout(700)
    chk("chave de envio do OneSignal também", pg.evaluate("navigator.clipboard.readText()") == "os_v2_app_FALSO_PARA_TESTE")
    chk("a chave NUNCA aparece na tela nem no aparelho", not SEGREDOS.search(pg.content()) and not SEGREDOS.search(pg.evaluate("JSON.stringify(localStorage)+JSON.stringify(sessionStorage)")))
    chk("o código de abertura vai junto em cada cópia", all(c.get("cofre") == "abc123COFRE" for c in st["cofre"]["chamadas"] if c.get("action") == "revelarConexao"))
    print("== Chaves do servidor das Mensagens (v7.38) ==")
    chk("senha errada foi conferida uma vez só (sem cair para o Apps Script e contar em dobro)", st["cofre"]["falhas"] == 1)
    chk("Zernio, Wafly e Gemini aparecem no cofre", all(pg.locator("[data-cx=cofre-copiar][data-nome='w:%s']" % n).count() == 1 for n in ("zernio", "wafly1", "gemini")))
    chk("Zernio mostra só o final da chave", "termina em 9z8y" in pg.inner_text("#cx-cofre"))
    chk("Gemini sem chave: botão desligado", pg.locator("[data-cx=cofre-copiar][data-nome='w:gemini']").is_disabled())
    pg.click("[data-cx=cofre-copiar][data-nome='w:zernio']"); pg.wait_for_timeout(700)
    chk("Zernio: chave copiada para a área de transferência", pg.evaluate("navigator.clipboard.readText()") == "sk_ZERNIO_FALSO_PARA_TESTE_9z8y" and "Copiada" in pg.inner_text("#cx-msg-cofre"))
    pg.click("[data-cx=cofre-copiar][data-nome='w:wafly1']"); pg.wait_for_timeout(700)
    chk("Wafly: instância e tokens juntos", "WAF_FALSO_PARA_TESTE" in pg.evaluate("navigator.clipboard.readText()"))
    chk("cópia do servidor leva o mesmo código de abertura", all(c.get("cofre") == "abc123COFRE" for c in st["cofre"]["chamadas"] if c.get("caminho") == "/cofre/revelar"))
    chk("e nada disso aparece na tela", not SEGREDOS.search(pg.content()))
    print("== Trancar ==")
    pg.click("[data-cx=cofre-trancar]"); pg.wait_for_timeout(500)
    chk("trancou na tela e no servidor", pg.locator("#cx-cofre-senha").is_visible() and st["cofre"]["codigo"] == "" and not st["ig"].get("cofre_w_aberto"))
    pg.fill("#cx-cofre-senha", "senha-certa"); pg.click("[data-cx=cofre-abrir]"); pg.wait_for_selector("[data-cx=cofre-copiar]")
    pg.evaluate("document.querySelector('#overlay-conexoes .sheet-x, #cx-fechar').click()"); pg.wait_for_timeout(600)
    chk("fechar a janela tranca o cofre no servidor", st["cofre"]["codigo"] == "")
    chk("nenhum erro de JavaScript", not erros, erros[:3])
    ctx.close()
    print("== Instagram no cofre (backend 4.3) ==")
    c3, p3, st3, e3 = novo(b, versao="4.3")
    chk("bloco do Instagram aparece nas Conexões, sem chave", p3.locator("#cx-bloco-instagram").count() == 1 and "Sem chave" in p3.inner_text("#cx-estado-instagram"))
    p3.fill("#cx-chave-instagram", "IGAA_FALSO_PARA_TESTE_123456"); p3.click("[data-cx=guardar][data-nome=instagram]"); p3.wait_for_timeout(900)
    chk("guardar liga o Worker (importador/postagens) E guarda a cópia no cofre", st3["ig"].get("token_recebido") == "IGAA_FALSO_PARA_TESTE_123456" and st3["chave_enviada"] == "IGAA_FALSO_PARA_TESTE_123456" and "Guardada" in p3.inner_text("#cx-msg-instagram"), p3.inner_text("#cx-msg-instagram"))
    chk("o token não fica no campo nem na tela", p3.input_value("#cx-chave-instagram") == "" and not SEGREDOS.search(p3.content()))
    p3.fill("#cx-cofre-senha", "senha-certa"); p3.click("[data-cx=cofre-abrir]"); p3.wait_for_selector("[data-cx=cofre-copiar]")
    chk("cofre aberto: 5 itens, o Instagram entre eles", p3.locator(AS).count() == 5 and p3.locator("[data-cx=cofre-copiar][data-nome=instagram]").count() == 1)
    p3.click("[data-cx=cofre-copiar][data-nome=instagram]"); p3.wait_for_timeout(700)
    chk("o token do Instagram vai para a área de transferência", p3.evaluate("navigator.clipboard.readText()") == "IGAA_FALSO_PARA_TESTE_123456")
    chk("e nunca aparece na tela", not SEGREDOS.search(p3.content()))
    c3.close()

    print("== Servidor das Mensagens fora do ar ==")
    c4, p4, st4, e4 = novo(b)
    st4["ig"]["cofre_fora"] = True
    p4.fill("#cx-cofre-senha", "senha-certa"); p4.click("[data-cx=cofre-abrir]"); p4.wait_for_selector("[data-cx=cofre-copiar]")
    chk("abre pelo Apps Script e mostra as 4 chaves de lá", p4.locator(AS).count() == 4 and p4.locator("[data-cx=cofre-copiar][data-nome^='w:']").count() == 0)
    p4.click("[data-cx=cofre-copiar][data-nome=render]"); p4.wait_for_timeout(700)
    chk("e continua copiando", p4.evaluate("navigator.clipboard.readText()") == "rnd_FALSO_PARA_TESTE_123456")
    chk("nenhum erro de JavaScript (fora do ar)", not e4, e4[:3])
    c4.close()

    print("== Quem não vê / backend antigo ==")
    c2, p2, st2, e2 = novo(b, versao="3.5")
    chk("backend 3.5 (sem a bandeira): nenhum cofre", p2.locator("#cx-cofre").count() == 0)
    c2.close()
    b.close()
print("\nOK=%d FALHAS=%d %s" % (len(OK), len(BAD), BAD))
sys.exit(1 if BAD else 0)
